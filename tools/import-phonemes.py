#!/usr/bin/env python3
"""Copies the recorded Australian English phoneme clips from the Phonics repo into
data/phonemes.json as base64, so the sound boxes page can play them with no network
call and no audio files in this repo (tools/check-public.py blocks .mp3).

  python3 tools/import-phonemes.py [path/to/Phonics]     (default: ../Phonics next to this repo)

Re-run it when a recording in Phonics/recordings/au/phonemes changes. Clips that
Phonics/recordings/clips.json lists as too short (cut off in export) are left out,
so the page falls back to saying nothing rather than playing a click."""
import base64, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PHONICS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'Phonics'
SRC = PHONICS / 'recordings' / 'au' / 'phonemes'
if not SRC.is_dir():
    print(f'not found: {SRC}'); sys.exit(1)

too_short = set()
report = PHONICS / 'recordings' / 'clips.json'
if report.is_file():
    too_short = set(json.loads(report.read_text(encoding='utf-8')).get('tooShort', []))

labels = {}
manifest = PHONICS / 'recordings' / 'au' / 'manifest.csv'
if manifest.is_file():
    import csv
    for row in csv.DictReader(manifest.read_text(encoding='utf-8').splitlines()):
        if row.get('kind') == 'phoneme':
            labels[row['id']] = row.get('notes', '')

clips, skipped = {}, []
for f in sorted(SRC.glob('*.mp3')):
    if f'recordings/au/phonemes/{f.name}' in too_short:
        skipped.append(f.stem); continue
    clips[f.stem] = base64.b64encode(f.read_bytes()).decode('ascii')

out = {
    '_about': 'GENERATED by tools/import-phonemes.py from the Phonics repo, recordings/au/phonemes/*.mp3 '
              '(human recordings, Australian English). Do not hand-edit: re-record in Phonics and re-run the script.',
    'labels': {k: labels.get(k, '') for k in clips},
    'clips': clips,
}
(ROOT / 'data' / 'phonemes.json').write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding='utf-8')
print(f'{len(clips)} clips written to data/phonemes.json' + (f'; skipped as too short: {", ".join(skipped)}' if skipped else ''))
